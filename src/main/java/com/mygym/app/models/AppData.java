package com.mygym.app.models;

public class AppData {
    private int nextBranchId;
    private long nextGrievanceId;
    private long nextNotificationId;
    
	public int getNextBranchId() {
		return nextBranchId;
	}
	public void setNextBranchId(int nextBranchId) {
		this.nextBranchId = nextBranchId;
	}
	public long getNextGrievanceId() {
		return nextGrievanceId;
	}
	public void setNextGrievanceId(long nextGrievanceId) {
		this.nextGrievanceId = nextGrievanceId;
	}
	public long getNextNotificationId() {
		return nextNotificationId;
	}
	public void setNextNotificationId(long nextNotificationId) {
		this.nextNotificationId = nextNotificationId;
	}


}
